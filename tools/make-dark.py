#!/usr/bin/env python3
"""tools/make-dark.py (v10.26.5): writes src/themes/dark.css, a dark colour set for EVERY theme found in src/themes/theme-*.css.
Run from the repo root after adding or changing a theme:   python3 tools/make-dark.py
Only colours are changed (never layout, fonts or radii). Each colour is nudged until it is readable (WCAG AA, 4.5:1) on the dark background."""
import re, glob, colorsys
def rgb(h): h=h.lstrip('#'); h=h*2 if len(h)==3 else h; return tuple(int(h[i:i+2],16)/255 for i in (0,2,4))
def hexs(c): return '#%02X%02X%02X'%tuple(round(max(0,min(1,v))*255) for v in c)
def hsl(h): r,g,b=rgb(h); hh,l,s=colorsys.rgb_to_hls(r,g,b); return hh,s,l
def mk(h,s,l): return hexs(colorsys.hls_to_rgb(h%1,max(0,min(1,l)),max(0,min(1,s))))
def lum(h):
    f=lambda v: v/12.92 if v<=.03928 else ((v+.055)/1.055)**2.4
    r,g,b=map(f,rgb(h)); return .2126*r+.7152*g+.0722*b
def cr(a,b): x,y=sorted([lum(a),lum(b)],reverse=True); return (x+.05)/(y+.05)
def readable(h,s,l,on,mn=4.5):   # raise lightness until the colour reads on `on`
    c=mk(h,s,l)
    while cr(c,on)<mn and l<.97: l+=.02; c=mk(h,s,l)
    return c
themes=[]
for f in sorted(glob.glob('src/themes/theme-*.css')):
    for m in re.finditer(r'\[data-theme="([\w-]+)"\]\s*\{(.*?)\n\}',open(f).read(),re.S):
        themes.append((m.group(1),dict(re.findall(r'--([\w-]+):\s*([^;]+);',m.group(2)))))
out=['/* dark.css (v10.26.5): GENERATED by tools/make-dark.py, do not edit by hand. A dark colour set for every theme.\n   It is only switched on when the site is opened from your own computer (see js/boot.js). Visitors never get a dark switch. */\n']
for name,t in themes:
    hh,hs,_=hsl(t['heading']); ah,as_,_=hsl(t['accent'])
    bh,bs=(hh,min(hs,.5)) if hs>=.15 else (ah,.10)     # neutral themes borrow a faint hue from the accent
    bg=mk(bh,min(bs*.6,.28),.075); surface=mk(bh,min(bs*.6,.26),.115); alt=mk(bh,min(bs*.6,.26),.165); border=mk(bh,min(bs*.55,.24),.26)
    text=mk(bh,min(bs,.22),.88); heading=mk(bh,min(bs,.30),.96)
    accent=readable(ah,min(as_,.75),.66,bg); lh,ls,_=hsl(t['link']); link=readable(lh,min(ls,.75),.68,bg)
    bb,bt=t['btn-bg'],t['btn-text']; bbh,bbs,bbl=hsl(bb)
    if cr(bb,bg)>=4.5: btnbg=bb.upper() if len(bb)==7 else bb
    else:
        th,ts,tl=hsl(bt)
        btnbg=bt.upper() if (ts>.5 and tl>=.5 and cr(bt,bg)>=4.5) else (readable(bbh,bbs,.92,bg) if bbs<.12 else readable(bbh,min(bbs,.7),.74,bg))
    btntext=bg if cr(bg,btnbg)>=cr('#FFFFFF',btnbg) else '#FFFFFF'
    out.append(f'''/* {name} (dark) */
html[data-mode="dark"][data-theme="{name}"],html[data-mode="dark"] [data-theme="{name}"]{{
  --bg:{bg}; --surface:{surface}; --surface-alt:{alt}; --border:{border};
  --text:{text}; --heading:{heading}; --accent:{accent};
  --btn-bg:{btnbg}; --btn-text:{btntext}; --link:{link}; --btn-invert-text:{btnbg};
  --shadow:0 6px 18px rgba(0,0,0,.5);
  color-scheme:dark;
}}
''')
out.append('''/* Everything below the colour sets: small fixes so nothing looks wrong on a dark page. */
html[data-mode="dark"] body{background:var(--bg);color:var(--text)}
html[data-mode="dark"] img[src*="logo-light"],html[data-mode="dark"] img[src*="logo-mark"]{filter:invert(.94)}   /* the black logo becomes cream */
html[data-mode="dark"] .specials{background:var(--surface-alt);color:var(--text);border-bottom:1px solid var(--border)}   /* the two ticker strips are dim, not bright bars */
html[data-mode="dark"] .specials--bottom{border-top:1px solid var(--border);border-bottom:0}
html[data-mode="dark"] .btn--whatsapp:hover{color:#6FE3A0}
/* theme-preview.html (local design page) */
html[data-mode="dark"] body:has(#themes){background:#0B0B0B}
html[data-mode="dark"] .page-head{color:#DDD}
html[data-mode="dark"] .logo-wrap img{filter:invert(.94);background:#000}
html[data-mode="dark"] .menu--glass .card,html[data-mode="dark"] .card--glass{box-shadow:0 10px 30px rgba(0,0,0,.45),inset 0 1px 0 rgba(255,255,255,.08)}
html[data-mode="dark"] .menu--glass .card:hover,html[data-mode="dark"] .menu--glass .card:focus-within{box-shadow:0 18px 40px rgba(0,0,0,.55),inset 0 1px 0 rgba(255,255,255,.12)}
html[data-mode="dark"] .form__error,html[data-mode="dark"] .notice--error{color:#FF9C94}
''')
open('src/themes/dark.css','w').write('\n'.join(out))
print(len(themes),'themes ->',len('\n'.join(out)),'bytes')
bad=0
